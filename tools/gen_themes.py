#!/usr/bin/env python3
"""Atlas themes: check every colour pair against WCAG AA, then write the phone's Themes.kt and the PC's CSS block.

  python3 tools/gen_themes.py          check + write
  python3 tools/gen_themes.py --check  check only (exit 1 on any failure)

Rules (WCAG 2.x contrast ratio):
  - text colours (fg, muted, faint, accentInk, blue, warm, done, danger) on bg, surface and surface2: >= 4.5
  - onPrimary on both ends of the primary button gradient: >= 4.5
  - accent (a fill / UI colour: orb tint, toggles, focus rings) against bg: >= 3.0
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TEXT = ["fg", "muted", "faint", "accentInk", "blue", "warm", "done", "danger"]
GROUNDS = ["bg", "surface", "surface2"]

def lum(h):
    h = h.lstrip('#'); r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)

def ratio(a, b):
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)

def check(data):
    rows, bad = [], []
    for t in data["themes"]:
        for mode in ("dark", "light"):
            p = t[mode]
            for k in TEXT:
                for g in GROUNDS:
                    r = ratio(p[k], p[g]); rows.append((t["id"], mode, k, g, r, 4.5))
                    if r < 4.5: bad.append(rows[-1])
            for g in ("primaryTop", "primaryBottom"):
                r = ratio(p["onPrimary"], p[g]); rows.append((t["id"], mode, "onPrimary", g, r, 4.5))
                if r < 4.5: bad.append(rows[-1])
            r = ratio(p["accent"], p["bg"]); rows.append((t["id"], mode, "accent", "bg", r, 3.0))
            if r < 3.0: bad.append(rows[-1])
    return rows, bad

def kt(data):
    def pal(p):
        f = ", ".join(f'{k} = c("{p[k]}")' for k in ["bg", "surface", "surface2", "line", "fg", "muted", "faint", "accent", "accentInk", "blue", "warm", "done", "danger", "primaryTop", "primaryBottom", "onPrimary", "nav"])
        return f"Palette({f})"
    out = ["package com.anjy.atlas", "", "import android.graphics.Color", "",
           "// GENERATED by tools/gen_themes.py from tools/themes.json — edit the JSON, not this file.", "",
           "/** Atlas's colour themes. Every text colour clears WCAG AA on bg, surface and surface2 (checked when generated). */",
           "object ThemeData {", "    private fun c(hex: String) = Color.parseColor(hex)",
           f'    const val DEFAULT = "{data["default"]}"', "    val ALL: List<Theme> = listOf("]
    items = []
    for t in data["themes"]:
        al = ", ".join(json.dumps(a) for a in t["aliases"])
        items.append(f'        Theme("{t["id"]}", "{t["name"]}", listOf({al}),\n            dark = {pal(t["dark"])},\n            light = {pal(t["light"])})')
    out.append(",\n".join(items)); out += ["    )", "}", ""]
    return "\n".join(out)

def rgbs(h):
    h = h.lstrip("#"); return ", ".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))

def mixhex(a, b, t):
    a = a.lstrip("#"); b = b.lstrip("#")
    return "#" + "".join(f"{int(int(a[i:i + 2], 16) + (int(b[i:i + 2], 16) - int(a[i:i + 2], 16)) * t):02X}" for i in (0, 2, 4))

def css(data):
    lines = ["/* >>> themes: GENERATED by tools/gen_themes.py from tools/themes.json — edit the JSON, not this block */"]
    for t in data["themes"]:
        for mode in ("dark", "light"):
            p = t[mode]
            sel = f':root[data-palette="{t["id"]}"]' + ('[data-theme="light"]' if mode == "light" else '')
            if t["id"] == data["default"] and mode == "dark": sel = ':root, ' + sel
            if t["id"] == data["default"] and mode == "light": sel = ':root[data-theme="light"]:not([data-palette]), ' + sel
            a1, a2 = p["aurora1"], p["aurora2"]
            n = t["dark"]
            lines.append(f'{sel} {{\n  --bg: {p["bg"]}; --bg2: {p["surface"]}; --surface2: {p["surface2"]}; --fg: {p["fg"]}; --muted: {p["muted"]}; --faint: {p["faint"]};\n'
                         f'  --accent: {p["accent"]}; --accent-ink: {p["accentInk"]}; --blue: {p["blue"]}; --warm: {p["warm"]}; --done: {p["done"]}; --miss: {p["danger"]};\n'
                         f'  --primary-a: {p["primaryTop"]}; --primary-b: {p["primaryBottom"]}; --on-primary: {p["onPrimary"]}; --nav: {p["nav"]};\n'
                         f'  --glow: rgba({a1}, {"0.40" if mode == "dark" else "0.28"}); --aurora1: rgba({a1}, {"0.16" if mode == "dark" else "0.30"}); --aurora2: rgba({a2}, {"0.14" if mode == "dark" else "0.24"});\n'
                         f'  --select: rgba({a1}, 0.35); --surface: {p["surface"]}; --line: {p["line"]};\n'
                         f'  --rim-low: rgba({a1 if mode == "dark" else rgbs(p["fg"])}, {"0.18" if mode == "dark" else "0.12"});\n'
                         # the always-dark screens (alarm, focus) use the theme's dark look even when the app is light
                         f'  --night-bg: {n["bg"]}; --night-top: {mixhex(n["bg"], n["accent"], 0.07)}; --night-bottom: {mixhex(n["bg"], "#000000", 0.18)};\n'
                         f'  --night-fg: {n["fg"]}; --night-muted: {n["muted"]}; --night-faint: {n["faint"]}; --night-glow: rgba({rgbs(n["accent"])}, 0.26);\n}}')
    lines.append("/* <<< themes */")
    return "\n".join(lines)

def main():
    data = json.load(open(os.path.join(HERE, "themes.json")))
    rows, bad = check(data)
    lo = min(rows, key=lambda r: r[4])
    print(f"{len(rows)} pairs checked; lowest {lo[4]:.2f} ({lo[0]} {lo[1]} {lo[2]} on {lo[3]})")
    for t in data["themes"]:
        for mode in ("dark", "light"):
            rs = [r for r in rows if r[0] == t["id"] and r[1] == mode]
            m = {k: min(r[4] for r in rs if r[2] == k) for k in TEXT + ["onPrimary", "accent"]}
            print(f'  {t["id"]:9s} {mode:5s} ' + "  ".join(f"{k}:{v:.1f}" for k, v in m.items()))
    if bad:
        for r in bad: print(f"FAIL {r[0]} {r[1]} {r[2]} on {r[3]}: {r[4]:.2f} < {r[5]}")
        sys.exit(1)
    if "--check" in sys.argv: return
    open(os.path.join(ROOT, "app/src/main/java/com/anjy/atlas/ThemeData.kt"), "w").write(kt(data))
    cp = os.path.join(ROOT, "desktop/renderer/style.css"); s = open(cp).read()
    block = css(data)
    if "/* >>> themes:" in s:
        s = re.sub(r"/\* >>> themes:.*?/\* <<< themes \*/", lambda m: block, s, flags=re.S)
    else:
        s = s + "\n" + block + "\n"
    open(cp, "w").write(s)
    open(os.path.join(ROOT, "desktop/renderer/themes.js"), "w").write(js(data))
    print("wrote ThemeData.kt, style.css theme block, renderer/themes.js")

def js(data):
    keep = ("bg", "surface", "fg", "muted", "accent", "blue")
    meta = [{"id": t["id"], "name": t["name"], "aliases": t["aliases"], "note": t["note"],
             "dark": {k: t["dark"][k] for k in keep}, "light": {k: t["light"][k] for k in keep}} for t in data["themes"]]
    return ("// GENERATED by tools/gen_themes.py from tools/themes.json — edit the JSON, not this file.\n"
            "// The colour themes for Me → Look (the CSS itself is the theme block in style.css).\n"
            f"export const DEFAULT = {json.dumps(data['default'])};\n"
            f"export const THEMES = {json.dumps(meta, indent=1)};\n"
            "/** \"gold\", \"the cyan one\", \"forest & coral\" → a theme, or null (the same matching as the phone's Themes.find). */\n"
            "export function findTheme(words) {\n"
            "  const w = String(words || '').trim().toLowerCase();\n"
            "  if (!w) return null;\n"
            "  const esc = (s) => s.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&');\n"
            "  return THEMES.find((t) => t.id === w || t.name.toLowerCase() === w)\n"
            "    || THEMES.find((t) => t.aliases.some((a) => w === a || new RegExp('\\\\b' + esc(a) + '\\\\b').test(w))) || null;\n"
            "}\n")

if __name__ == "__main__": main()
